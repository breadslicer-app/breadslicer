#[test]
fn quotes_in_a_message_are_escaped_in_the_code() {
    let code = catalog_code(
        &bundle(&[("es", ES)]),
        &messages(r#"fn f() { ctr!("Menu", "Say \"hi\""); }"#),
    );
    assert!(
        code.contains(
            r#"        id: "Say \"hi\"",
        translations: &[Some("Say \"hi\""), Some("Di \"hola\"")],"#
        ),
        "{code}"
    );
}
