/// The 2 previews UVtools writes for Klipper: `preview.png` the small one,
/// `preview_cropping.png` the large.
pub const PREVIEW_SIZES: PreviewSizes = PreviewSizes {
    small: PreviewSize {
        width: 32,
        height: 32,
    },
    large: PreviewSize {
        width: 400,
        height: 300,
    },
};

pub(crate) const MARKER_FILE: &str = ".klipper";
const JOB_NAME: &str = "breadslicer";

pub(crate) fn gcode_file() -> String {
    format!("{JOB_NAME}.gcode")
}

/// Klipper's G-code: absolute moves in mm/min, waits in milliseconds, `G1`
/// for every move.
fn dialect() -> Dialect {
    Dialect {
        layer_move: MoveCommand::G1,
        end_move: MoveCommand::G1,
        ..Dialect::default()
    }
    .klipper()
}

/// What a layer covers, in the figures the G-code states.
#[derive(Clone, Copy, Debug, Default)]
struct Figures {
    pixels: u64,
    /// `x, y, width, height` in millimetres.
    bounds_mm: [f32; 4],
    area_mm2: f32,
    volume_mm3: f32,
    ml: f32,
}

struct Machine {
    pixel_mm: (f32, f32),
    layer_count: usize,
    print_height: f32,
    volume_mm3: f32,
    ml: f32,
    grams: f32,
    material: String,
    print_time_sec: f32,
    layer_height: f32,
    created: String,
    bounds_mm: [f32; 4],
    bounds_px: [u32; 4],
    resolution: (u32, u32),
}

struct KlipperHooks<'a> {
    machine: &'a Machine,
    layers: &'a [GLayer],
    figures: &'a [Figures],
}

fn rect(bounds: [f32; 4]) -> String {
    format!(
        "{},{},{},{}",
        num(bounds[0]),
        num(bounds[1]),
        num(bounds[2]),
        num(bounds[3])
    )
}

/// A length of time as UVtools writes one: `1h 02m 03s`.
fn time_string(seconds: f32) -> String {
    let total = seconds.max(0.0).round() as u64;
    let (hours, minutes, secs) = (total / 3600, total / 60 % 60, total % 60);
    if hours > 0 {
        format!("{hours}h {minutes:02}m {secs:02}s")
    } else if minutes > 0 {
        format!("{minutes}m {secs:02}s")
    } else {
        format!("{secs}s")
    }
}

impl Hooks for KlipperHooks<'_> {
    fn before_rebuild(&mut self, g: &mut Builder) {
        g.comment(&format!(
            " generated by PrusaSlicer 2.7.4+win-x64 on {} UTC",
            self.machine.created
        ));
    }

    fn before_start(&mut self, g: &mut Builder) -> bool {
        let m = self.machine;
        g.line(&format!(
            "MSLA_DISPLAY_VALIDATE RESOLUTION={},{} PIXEL={},{}",
            m.resolution.0,
            m.resolution.1,
            num(m.pixel_mm.0),
            num(m.pixel_mm.1)
        ));
        let name = if m.material.trim().is_empty() {
            String::new()
        } else {
            format!(" MATERIAL_NAME=\"{}\"", m.material)
        };
        g.line(&format!(
            "SET_PRINT_STATS_INFO TOTAL_LAYER={} LAYER=1 MATERIAL_TOTAL={}{name}",
            m.layer_count,
            num(m.ml)
        ));
        g.line(&format!(
            "PRINT_START LAYERS={} HEIGHT={} BOUNDS={} VOLUME={} MATERIALML={}",
            m.layer_count,
            num(m.print_height),
            rect(m.bounds_mm),
            num(m.volume_mm3),
            num(m.ml)
        ));
        true
    }

    fn before_layer(&mut self, g: &mut Builder, index: usize) -> bool {
        let layer = &self.layers[index];
        let f = self.figures.get(index).copied().unwrap_or_default();
        g.line(&format!("SET_PRINT_STATS_INFO CURRENT_LAYER={}", index + 1));
        g.line(&format!(
            "BEFORE_LAYER_CHANGE LAYER={} HEIGHT={} PIXELS={} BOUNDS={} AREA={} VOLUME={} MATERIALML={}",
            index + 1,
            num(layer.position_z),
            f.pixels,
            rect(f.bounds_mm),
            num(f.area_mm2),
            num(f.volume_mm3),
            num(f.ml)
        ));
        false
    }

    fn after_layer(&mut self, g: &mut Builder, index: usize) {
        let f = self.figures.get(index).copied().unwrap_or_default();
        g.line(&format!(
            "SET_PRINT_STATS_INFO CONSUME_MATERIAL={}",
            num(f.ml)
        ));
        g.line("AFTER_LAYER_CHANGE");
    }

    fn before_end(&mut self, g: &mut Builder) -> bool {
        g.line("PRINT_END");
        true
    }

    fn after_rebuild(&mut self, g: &mut Builder) {
        let m = self.machine;
        let first = self.layers.first();
        g.blank();
        g.comment(&format!(" total layers count = {}", m.layer_count));
        g.comment(&format!(" layer_height = {}", num(m.layer_height)));
        g.comment(&format!(
            " first_layer_height = {}",
            num(first.map_or(0.0, |l| l.position_z))
        ));
        g.comment(&format!(" resin name = {}", m.material));
        g.comment(&format!(" resin used [ml] = {}", num(m.ml)));
        g.comment(&format!(" resin used [g] = {}", num(m.grams)));
        g.comment(" resin cost = 0");
        g.comment(&format!(
            " estimated printing time = {}",
            time_string(m.print_time_sec)
        ));
        g.comment(&format!(
            " estimated first layer printing time = {}",
            time_string(first.map_or(0.0, |l| l.print_time_sec))
        ));
    }
}

/// The settings block, as UVtools states Klipper's header.
fn header(program: &PrintProgram, machine: &Machine) -> String {
    let summary = ProgramSummary::of(program);
    let (b, n) = (summary.bottom, summary.normal);
    let raster = &program.raster;
    let (width_mm, height_mm) = raster.panel_size_mm();
    let mirror = raster.mirror();
    let r2 = |value: f32| num(round_away(value, 2));
    // Without a second stage its speeds are the first stage's: no speed reads
    // as zero.
    let second = |stage: Option<(f32, f32, f32)>, lift: f32, retract: f32| {
        stage.unwrap_or((0.0, lift, retract))
    };
    let b2 = second(b.second_stage, b.lift_mm_min, b.retract_mm_min);
    let n2 = second(n.second_stage, n.lift_mm_min, n.retract_mm_min);
    let rect_px = machine.bounds_px;
    let lines: Vec<(&str, String)> = vec![
        ("FileName", format!("{JOB_NAME}.zip")),
        ("MachineName", program.machine_name.as_str().to_owned()),
        ("PrintTime", num(round_away(machine.print_time_sec, 3))),
        ("Volume", num(machine.volume_mm3)),
        ("MaterialName", machine.material.clone()),
        ("MaterialGrams", num(machine.grams)),
        ("MaterialMl", num(machine.ml)),
        ("Price", "0".to_owned()),
        ("LayerHeight", num(machine.layer_height)),
        ("ResolutionX", machine.resolution.0.to_string()),
        ("ResolutionY", machine.resolution.1.to_string()),
        ("MachineX", num(round_display(width_mm as f32))),
        ("DisplayHeight", num(round_display(height_mm as f32))),
        (
            "MachineZ",
            num(round_away(raster.build_volume().z().value() as f32, 2)),
        ),
        ("Mirror", u8::from(mirror.x || mirror.y).to_string()),
        ("LayerCount", machine.layer_count.to_string()),
        ("BottomLayerCount", program.bottom_layer_count.to_string()),
        (
            "TransitionLayerCount",
            program.transition_layer_count.to_string(),
        ),
        ("BottomWaitTimeBeforeCure", r2(b.wait_before_cure_sec)),
        ("WaitTimeBeforeCure", r2(n.wait_before_cure_sec)),
        ("BottomExposureTime", r2(b.exposure_sec)),
        ("ExposureTime", r2(n.exposure_sec)),
        ("BottomWaitTimeAfterCure", r2(b.wait_after_cure_sec)),
        ("WaitTimeAfterCure", r2(n.wait_after_cure_sec)),
        ("BottomLiftHeight", r2(b.lift_mm)),
        ("BottomLiftSpeed", r2(b.lift_mm_min)),
        ("BottomLiftAcceleration", "0".to_owned()),
        ("BottomLiftHeight2", r2(b2.0)),
        ("BottomLiftSpeed2", r2(b2.1)),
        ("BottomLiftAcceleration2", "0".to_owned()),
        ("BottomRetractSpeed", r2(b.retract_mm_min)),
        ("BottomRetractAcceleration", "0".to_owned()),
        ("BottomRetractHeight2", r2(b2.0)),
        ("BottomRetractSpeed2", r2(b2.2)),
        ("BottomRetractAcceleration2", "0".to_owned()),
        ("LiftHeight", r2(n.lift_mm)),
        ("LiftSpeed", r2(n.lift_mm_min)),
        ("LiftAcceleration", "0".to_owned()),
        ("LiftHeight2", r2(n2.0)),
        ("LiftSpeed2", r2(n2.1)),
        ("LiftAcceleration2", "0".to_owned()),
        ("RetractSpeed", r2(n.retract_mm_min)),
        ("RetractAcceleration", "0".to_owned()),
        ("RetractHeight2", r2(n2.0)),
        ("RetractSpeed2", r2(n2.2)),
        ("RetractAcceleration2", "0".to_owned()),
        ("BottomWaitTimeAfterLift", r2(b.wait_after_lift_sec)),
        ("WaitTimeAfterLift", r2(n.wait_after_lift_sec)),
        ("BottomLightPWM", b.pwm.to_string()),
        ("LightPWM", n.pwm.to_string()),
        ("AntiAliasing", raster.aa().factor().to_string()),
        (
            "BoundingRectanglePx",
            format!(
                "{{X={},Y={},Width={},Height={}}}",
                rect_px[0], rect_px[1], rect_px[2], rect_px[3]
            ),
        ),
        (
            "BoundingRectangleMm",
            format!(
                "{{X={},Y={},Width={},Height={}}}",
                num(machine.bounds_mm[0]),
                num(machine.bounds_mm[1]),
                num(machine.bounds_mm[2]),
                num(machine.bounds_mm[3])
            ),
        ),
    ];
    let mut text = String::new();
    for (key, value) in lines {
        let value = value.replace(['\r', '\n'], " ");
        text.push_str(&format!(";{key}:{value}\n"));
    }
    text
}

struct Encoded {
    png: Result<Vec<u8>, png::EncodingError>,
    stats: LayerStats,
}

fn encode(rows: &[RleRun], width: u32, height: u32) -> Encoded {
    let mut pixels = Vec::with_capacity(width as usize * height as usize);
    for run in rows {
        pixels.extend(std::iter::repeat_n(run.value, run.length as usize));
    }
    Encoded {
        png: grey_png(&pixels, width, height),
        stats: LayerStats::of(rows, width),
    }
}

/// A date and time as `MM/dd/yyyy at HH:mm`.
fn created(unix_sec: u64) -> String {
    let days = (unix_sec / 86_400) as i64;
    let rest = unix_sec % 86_400;
    let z = days + 719_468;
    let era = z.div_euclid(146_097);
    let doe = z.rem_euclid(146_097);
    let yoe = (doe - doe / 1460 + doe / 36_524 - doe / 146_096) / 365;
    let doy = doe - (365 * yoe + yoe / 4 - yoe / 100);
    let mp = (5 * doy + 2) / 153;
    let day = doy - (153 * mp + 2) / 5 + 1;
    let month = if mp < 10 { mp + 3 } else { mp - 9 };
    let year = yoe + era * 400 + i64::from(month <= 2);
    format!(
        "{month:02}/{day:02}/{year} at {:02}:{:02}",
        rest / 3600,
        rest / 60 % 60
    )
}

/// Writes `stack` as a Klipper resin ZIP running the settings in `program`.
///
/// # Errors
///
/// [`WriteFailure::PreviewSize`] when a rendering is not the size this format
/// fixes, raised before any byte is written, and [`WriteFailure::Io`] when the
/// archive cannot be written.
pub fn write_file(
    program: &PrintProgram,
    previews: Option<&PrintPreviews>,
    stack: &ContourStack,
    out: &mut dyn PrinterFileSink,
) -> Result<(), WriteFailure> {
    let (small, large) = previews_or_black(previews, PREVIEW_SIZES)?;
    let panel = program.raster.panel_resolution();
    let (width, height) = (panel.x(), panel.y());
    let (width_mm, height_mm) = program.raster.panel_size_mm();
    let pixel_mm = (
        round_away(width_mm as f32 / width as f32, 4),
        round_away(height_mm as f32 / height as f32, 4),
    );
    let layers = layers_of(program);
    let options = SimpleFileOptions::default().compression_method(zip::CompressionMethod::Deflated);
    let mut zip = ZipWriter::new(out);

    // The layers first: the G-code states what each covers.
    let mut figures = Vec::with_capacity(layers.len());
    let mut bounds_px: Option<[u32; 4]> = None;
    let mut previous_z = 0.0_f32;
    write_layer_images(
        stack,
        &program.raster,
        1,
        |_, rows| encode(rows, width, height),
        |index, encoded: Encoded| -> Result<(), WriteFailure> {
            let png = encoded
                .png
                .map_err(|err| WriteFailure::Io(io::Error::other(err)))?;
            let z = layers.get(index).map_or(previous_z, |l| l.position_z);
            let thickness = round_height(z - previous_z);
            previous_z = z;
            let pixels = encoded.stats.lit_pixels;
            let area = round_away(pixels as f32 * pixel_mm.0 * pixel_mm.1, 3);
            let volume = round_away(area * thickness, 3);
            let rect = encoded
                .stats
                .bounds
                .map_or([0; 4], |b| [b.x0, b.y0, b.width(), b.y1 - b.y0]);
            if encoded.stats.bounds.is_some() {
                bounds_px = Some(match bounds_px {
                    None => rect,
                    Some(r) => {
                        let x0 = r[0].min(rect[0]);
                        let y0 = r[1].min(rect[1]);
                        let x1 = (r[0] + r[2]).max(rect[0] + rect[2]);
                        let y1 = (r[1] + r[3]).max(rect[1] + rect[3]);
                        [x0, y0, x1 - x0, y1 - y0]
                    }
                });
            }
            figures.push(Figures {
                pixels,
                bounds_mm: mm_rect(rect, pixel_mm),
                area_mm2: area,
                volume_mm3: volume,
                ml: round_away(volume / 1000.0, 4),
            });
            entry(&mut zip, &format!("{}.png", index + 1), &png, options)
        },
    )?;

    let volume_mm3 = round_away(figures.iter().map(|f| f.volume_mm3).sum(), 3);
    let bounds_px = bounds_px.unwrap_or([0; 4]);
    let machine = Machine {
        pixel_mm,
        layer_count: layers.len(),
        print_height: layers.last().map_or(0.0, |l| l.position_z),
        volume_mm3,
        ml: round_away(volume_mm3 / 1000.0, 3),
        grams: round_away(program.mass_g.value() as f32, 3),
        material: program.material_name.as_str().to_owned(),
        print_time_sec: program.print_time_sec.value() as f32,
        layer_height: round_height(program.layer_height_mm.value() as f32),
        created: created(program.created_at.unix_sec),
        bounds_mm: mm_rect(bounds_px, pixel_mm),
        resolution: (width, height),
        bounds_px,
    };
    let mut job = Job::new(program, &layers);
    for preview in [&small, &large] {
        let png = png_bytes(preview).map_err(|err| WriteFailure::Io(io::Error::other(err)))?;
        job.thumbnails
            .push((preview.width(), preview.height(), png));
    }
    let mut builder = Builder::new(dialect());
    let mut hooks = KlipperHooks {
        machine: &machine,
        layers: &layers,
        figures: &figures,
    };
    builder.rebuild(&job, &header(program, &machine), &mut hooks);

    entry(&mut zip, MARKER_FILE, b"", options)?;
    entry(&mut zip, &gcode_file(), builder.text().as_bytes(), options)?;
    for (name, (_, _, png)) in [PREVIEW_FILE, PREVIEW_CROPPING_FILE]
        .into_iter()
        .zip(&job.thumbnails)
    {
        entry(&mut zip, name, png, options)?;
    }
    zip.finish().map_err(zip_failure)?;
    Ok(())
}

fn mm_rect(rect: [u32; 4], pixel_mm: (f32, f32)) -> [f32; 4] {
    [
        round_away(rect[0] as f32 * pixel_mm.0, 2),
        round_away(rect[1] as f32 * pixel_mm.1, 2),
        round_away(rect[2] as f32 * pixel_mm.0, 2),
        round_away(rect[3] as f32 * pixel_mm.1, 2),
    ]
}

