//! The Klipper layout of the resin ZIP: `.zip` for the UnizMaker IBEE running
//! Klipper (#778).
//!
//! As ChiTuBox's ZIP, it holds the layers as `1.png`, `2.png`, ... and 2
//! previews; the G-code, named after the job, drives Klipper's resin macros
//! (`M1451` shows a layer, `M1400` exposes it) and states each layer's
//! figures for its print statistics. An empty `.klipper` entry marks the
//! layout.

