"""Check tracked corpus identities; optionally compare a fresh Rust generation.

This is byte/manifest verification, NOT a substitute for the Rust core checks.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def check(directory):
    manifest = json.loads((directory / "MANIFEST.json").read_text(encoding="utf-8"))
    assert manifest["schema"] == 1 and manifest["task"] == "SC-24"
    cases = manifest["cases"]
    assert len({c["id"] for c in cases}) == len(cases), "duplicate case IDs"
    expected_files = {"MANIFEST.json"}
    for case in cases:
        assert case["source"] and case["license"] and case["expected"]
        for item in case["artifacts"]:
            assert Path(item["path"]).name == item["path"], "artifact must be a plain filename"
            assert item["path"] not in expected_files, "duplicate artifact"
            expected_files.add(item["path"])
            data = (directory / item["path"]).read_bytes()
            assert len(data) == item["bytes"], item["path"]
            assert hashlib.sha256(data).hexdigest() == item["sha256"], item["path"]
    assert {p.name for p in directory.iterdir()} == expected_files, "unexpected/missing files"
    return manifest, expected_files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--compare", type=Path, help="fresh directory generated by the Rust example")
    args = parser.parse_args()
    reference = ROOT / "fixtures/sc-corpus/v1"
    manifest, files = check(reference)
    if args.compare:
        other, other_files = check(args.compare)
        assert manifest == other and files == other_files, "generation manifest drift"
        for name in files:
            assert (reference / name).read_bytes() == (args.compare / name).read_bytes(), name
    print(json.dumps({"cases": len(manifest["cases"]), "artifacts": len(files) - 1,
                      "hashes": "passed", "fresh_generation_byte_comparison": bool(args.compare)}))


if __name__ == "__main__":
    main()
