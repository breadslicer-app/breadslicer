/// A UVtools profile with the panel, mirror, height and notes given.
fn uvtools_profile(
    width: &str,
    depth: &str,
    pixels: (u32, u32),
    mirror_x: u8,
    height: u32,
    notes: &str,
) -> String {
    format!(
        "# generated by PrusaSlicer 2.8.1+win64\n\
bed_shape = 0x0\n\
display_height = {depth}\n\
display_mirror_x = {mirror_x}\n\
display_mirror_y = 0\n\
display_orientation = landscape\n\
display_pixels_x = {}\n\
display_pixels_y = {}\n\
display_width = {width}\n\
max_print_height = {height}\n\
printer_model = SL1\n\
printer_notes = Don't remove the following keywords!\\nPRINTER_VENDOR_PRUSA3D\\nPRINTER_MODEL_SL1\\n{notes}\\n\\nSTART_CUSTOM_VALUES\\nLiftHeight_8\\nLiftSpeed_120\\nEND_CUSTOM_VALUES\n",
        pixels.0, pixels.1,
    )
}

/// A profile we ship, with the panel, mirror, formats and capabilities
/// given.
#[allow(clippy::too_many_arguments)]
fn our_profile(
    id: &str,
    manufacturer: &str,
    name: &str,
    plate: (f64, f64, f64),
    pixels: (u32, u32),
    mirror_x: bool,
    rotation: &str,
    formats: &[(&str, &str)],
) -> String {
    let pixel_x = plate.0 * 1000.0 / f64::from(pixels.0);
    let pixel_y = plate.1 * 1000.0 / f64::from(pixels.1);
    let formats: String = formats
        .iter()
        .map(|(format, version)| {
            format!("\n[[capabilities.output_formats]]\nformat = \"{format}\"\nversion = \"{version}\"\n")
        })
        .collect();
    format!(
        "[identity]\n\
id = \"{id}\"\n\
manufacturer = \"{manufacturer}\"\n\
family = \"Ours\"\n\
name = \"{name}\"\n\
profile_version = \"2.0.0\"\n\
image_asset_path = \"images/{id}.png\"\n\
\n\
[hardware]\n\
{rotation}\n\
[hardware.build_volume]\n\
x_mm = {:?}\n\
y_mm = {:?}\n\
z_mm = {:?}\n\
\n\
[hardware.pixel_resolution]\n\
x = {}\n\
y = {}\n\
\n\
[hardware.pixel_size_microns]\n\
x = {pixel_x:?}\n\
y = {pixel_y:?}\n\
\n\
[hardware.mirror]\n\
x = {mirror_x}\n\
y = false\n\
\n\
[capabilities]\n\
supports_grayscale = true\n\
two_stage_lift = true\n\
transition_layers = 6\n\
has_camera = false\n\
{formats}\n\
[constraints]\n",
        plate.0, plate.1, plate.2, pixels.0, pixels.1,
    )
}

struct Fixture {
    _dir: TempDir,
    library: PathBuf,
    catalog: PathBuf,
    out: PathBuf,
}

impl Fixture {
    fn new() -> Self {
        let dir = tempfile::tempdir().unwrap();
        let library = dir.path().join("library");
        let catalog = dir.path().join("catalog");
        let out = dir.path().join("out");
        fs::create_dir_all(library.join("printers")).unwrap();
        fs::create_dir_all(&catalog).unwrap();
        fs::create_dir_all(&out).unwrap();
        Self {
            _dir: dir,
            library,
            catalog,
            out,
        }
    }

    fn ours(&self, id: &str, toml: String) -> &Self {
        fs::write(
            self.library.join("printers").join(format!("{id}.toml")),
            toml,
        )
        .unwrap();
        self
    }

    fn uvtools(&self, title: &str, ini: String) -> &Self {
        fs::write(self.catalog.join(format!("{title}.ini")), ini).unwrap();
        self
    }

    fn run(&self) -> RunReport {
        let request = ConversionRequest::from_raw(RawCliArgs {
            format: SourceFormat::UvtoolsCatalog,
            inputs: vec![self.catalog.clone()],
            out: self.out.clone(),
            with_images: false,
            printer_library: Some(self.library.clone()),
            material_curation: None,
        })
        .unwrap();
        run(&request).unwrap()
    }

    fn written(&self, id: &str) -> Option<PrinterProfile> {
        let path = self.out.join("printers").join(format!("{id}.toml"));
        path.is_file()
            .then(|| load_printer_profile_from_path(&path).unwrap())
    }
}

fn formats(profile: &PrinterProfile) -> Vec<String> {
    profile
        .capabilities
        .output_formats
        .iter()
        .map(ToString::to_string)
        .collect()
}

