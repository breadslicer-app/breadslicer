fn has(report: &RunReport, wanted: impl Fn(&SourceNote) -> bool) -> bool {
    report.notes.iter().any(wanted)
}

#[test]
fn a_machine_we_do_not_ship_becomes_a_profile_with_uvtools_figures() {
    let fixture = the_catalog();
    fixture.run();

    let profile = fixture.written("phrozen-sonic-mighty-8k").unwrap();
    assert_eq!(profile.identity.manufacturer.as_str(), "Phrozen");
    assert_eq!(profile.identity.family.as_str(), "Sonic");
    assert_eq!(profile.identity.name.as_str(), "Sonic Mighty 8K");
    assert_eq!(profile.identity.image_asset_path, None);
    let plate = profile.hardware.build_volume();
    assert_eq!(
        (plate.x_mm(), plate.y_mm(), plate.z_mm()),
        (218.88, 123.12, 235.0)
    );
    assert_eq!(profile.hardware.pixel_size_microns().x.value(), 28.5);
    assert!(profile.hardware.mirror().x && !profile.hardware.mirror().y);
    assert_eq!(formats(&profile), ["ctb@v5enc"]);
    assert!(!profile.capabilities.two_stage_lift);
    assert_eq!(profile.capabilities.transition_layers, None);
}

#[test]
