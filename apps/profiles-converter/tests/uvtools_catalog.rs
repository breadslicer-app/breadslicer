#[test]
fn a_turned_plate_that_stores_uvtools_panel_is_left_alone() {
    let fixture = the_catalog();
    let report = fixture.run();

    assert!(fixture.written("creality-halot-one").is_none());
    assert!(!report.notes.iter().any(|note| matches!(
        note,
        SourceNote::PanelFollowsUvtools { printer, .. }
            | SourceNote::MirrorFollowsUvtools { printer, .. }
            | SourceNote::FormatAddedFromUvtools { printer, .. }
            if printer.as_str() == "creality-halot-one"
    )));
    // The turn stays ours, so the rotation is not UVtools' to remove.
    let ours = load_printer_profile_from_path(
        &fixture
            .library
            .join("printers")
            .join("creality-halot-one.toml"),
    )
    .unwrap();
    assert_eq!(ours.hardware.panel_rotation(), PanelRotation::Ccw90);
}

