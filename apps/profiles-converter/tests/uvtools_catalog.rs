#[test]
fn a_shipped_machine_takes_uvtools_panel_and_mirror_and_keeps_the_rest() {
    let fixture = the_catalog();
    let report = fixture.run();

    let profile = fixture.written("anycubic-photon-s").unwrap();
    let hardware = profile.hardware;
    assert_eq!(
        (
            hardware.pixel_resolution().x(),
            hardware.pixel_resolution().y()
        ),
        (1440, 2560)
    );
    let plate = hardware.build_volume();
    assert_eq!((plate.x_mm(), plate.y_mm()), (68.04, 120.96));
    assert_eq!(hardware.pixel_size_microns().x.value(), 47.25);
    assert!(hardware.mirror().x);
    assert_eq!(
        profile.identity.image_asset_path.as_ref().unwrap().as_str(),
        "images/anycubic-photon-s.png"
    );
    assert_eq!(profile.identity.family.as_str(), "Ours");
    assert_eq!(profile.identity.profile_version.to_string(), "2.0.0");
    assert!(profile.capabilities.two_stage_lift);
    assert_eq!(profile.capabilities.transition_layers, Some(6));
    assert_eq!(formats(&profile), ["aff@pws"]);
    assert!(has(&report, |note| matches!(
        note,
        SourceNote::PanelFollowsUvtools { printer, .. } if printer.as_str() == "anycubic-photon-s"
    )));
    assert!(has(&report, |note| matches!(
        note,
        SourceNote::MirrorFollowsUvtools { printer, .. } if printer.as_str() == "anycubic-photon-s"
    )));
}

#[test]
fn uvtools_file_joins_ours_first_and_its_height_replaces_ours() {
    let fixture = the_catalog();
    let report = fixture.run();

    let profile = fixture.written("elegoo-saturn-3").unwrap();
    assert_eq!(formats(&profile), ["goo@v3.0", "ctb@v5enc"]);
    assert_eq!(profile.hardware.build_volume().z_mm(), 250.0);
    assert_eq!(profile.hardware.build_volume().x_mm(), 218.88);
    assert!(has(&report, |note| matches!(
        note,
        SourceNote::FormatAddedFromUvtools { printer, format }
            if printer.as_str() == "elegoo-saturn-3" && format == "goo@v3.0"
    )));
    assert!(has(&report, |note| matches!(
        note,
        SourceNote::HeightFollowsUvtools { printer, .. } if printer.as_str() == "elegoo-saturn-3"
    )));
}

