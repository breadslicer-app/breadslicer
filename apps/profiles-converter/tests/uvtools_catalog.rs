#[test]
fn a_regeneration_over_its_own_output_changes_nothing() {
    let fixture = the_catalog();
    fixture.run();
    // The output becomes the library the next run merges into.
    for entry in fs::read_dir(fixture.out.join("printers")).unwrap() {
        let path = entry.unwrap().path();
        fs::copy(
            &path,
            fixture
                .library
                .join("printers")
                .join(path.file_name().unwrap()),
        )
        .unwrap();
    }
    fs::remove_dir_all(fixture.out.join("printers")).unwrap();

    let report = fixture.run();

    assert!(!fixture.out.join("printers").exists() || is_empty(&fixture.out.join("printers")));
    assert!(!report.notes.iter().any(|note| matches!(
        note,
        SourceNote::PanelFollowsUvtools { .. }
            | SourceNote::MirrorFollowsUvtools { .. }
            | SourceNote::HeightFollowsUvtools { .. }
            | SourceNote::FormatAddedFromUvtools { .. }
    )));
}

fn is_empty(dir: &Path) -> bool {
    fs::read_dir(dir).unwrap().next().is_none()
}
