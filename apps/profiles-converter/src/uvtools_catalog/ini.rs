//! The PrusaSlicer printer profiles UVtools bundles, read as text.
//!
//! Each file is a list of `key = value` lines under a comment naming the
//! PrusaSlicer build that wrote it. `printer_notes` holds keywords
//! separated by a literal `\n`: PrusaSlicer's own vendor and model
//! keywords, then UVtools' `FILEFORMAT_<extension>` and its options, then
//! the print values UVtools starts a converted file from, between
//! `START_CUSTOM_VALUES` and `END_CUSTOM_VALUES`.

use std::collections::BTreeMap;

/// The separator PrusaSlicer writes between the lines of a note.
const NOTE_SEPARATOR: &str = "\\n";

/// One printer profile's values, by key.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub(crate) struct IniFile {
    values: BTreeMap<String, String>,
}

impl IniFile {
    /// Read every `key = value` line of `text`. Comments, blank lines and
    /// lines without an `=` are not values.
    pub(crate) fn parse(text: &str) -> Self {
        let values = text
            .trim_start_matches('\u{feff}')
            .lines()
            .filter(|line| !line.starts_with('#'))
            .filter_map(|line| line.split_once('='))
            .map(|(key, value)| (key.trim().to_owned(), value.trim().to_owned()))
            .filter(|(key, _)| !key.is_empty())
            .collect();
        Self { values }
    }

    /// The value `key` holds, when the profile states one.
    pub(crate) fn get(&self, key: &str) -> Option<&str> {
        self.values.get(key).map(String::as_str)
    }

    /// The keywords of the printer's notes that UVtools reads before its
    /// print values, in the order they are written.
    pub(crate) fn keywords(&self) -> impl Iterator<Item = &str> {
        self.get("printer_notes")
            .unwrap_or_default()
            .split(NOTE_SEPARATOR)
            .map(str::trim)
            .take_while(|line| *line != "START_CUSTOM_VALUES")
            .filter(|line| !line.is_empty())
    }

    /// The value a `<prefix>_<value>` keyword of the notes carries.
    pub(crate) fn keyword(&self, prefix: &str) -> Option<&str> {
        self.keywords().find_map(|line| {
            line.strip_prefix(prefix)
                .and_then(|rest| rest.strip_prefix('_'))
                .filter(|value| !value.is_empty())
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const PROFILE: &str = "\u{feff}# generated by PrusaSlicer 2.8.1+win64\n\
display_width = 223.642\n\
display_pixels_x = 13312\n\
bed_custom_model = \n\
printer_notes = Don't remove the following keywords!\\nPRINTER_VENDOR_PRUSA3D\\nPRINTER_VENDOR_ANYCUBIC\\nFILEFORMAT_PWSZ\\nFILEVERSION_1\\n\\nSTART_CUSTOM_VALUES\\nFILECLASS_NOTAKEYWORD\\nLiftHeight_8\\nEND_CUSTOM_VALUES\n";

    #[test]
    fn values_are_read_by_key_and_trimmed() {
        let ini = IniFile::parse(PROFILE);

        assert_eq!(ini.get("display_width"), Some("223.642"));
        assert_eq!(ini.get("display_pixels_x"), Some("13312"));
        assert_eq!(ini.get("bed_custom_model"), Some(""));
        assert_eq!(ini.get("display_height"), None);
    }

    #[test]
    fn the_comment_heading_the_file_is_no_value() {
        let ini = IniFile::parse(PROFILE);

        assert!(ini.values.keys().all(|key| !key.starts_with('#')));
    }

    #[test]
    fn keywords_stop_where_the_print_values_start() {
        let ini = IniFile::parse(PROFILE);

        assert_eq!(ini.keyword("FILEFORMAT"), Some("PWSZ"));
        assert_eq!(ini.keyword("FILEVERSION"), Some("1"));
        assert_eq!(ini.keyword("FILECLASS"), None);
        assert!(ini.keywords().all(|line| line != "LiftHeight_8"));
    }

    #[test]
    fn a_profile_without_notes_has_no_keywords() {
        let ini = IniFile::parse("display_width = 10\n");

        assert_eq!(ini.keywords().count(), 0);
        assert_eq!(ini.keyword("FILEFORMAT"), None);
    }
}
