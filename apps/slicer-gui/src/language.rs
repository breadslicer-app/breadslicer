//! Language preference: catalogue of bundled locales and the runtime
//! plumbing that switches between them.
//!
//! The user-visible setting is `Option<String>`:
//! * `None` → "system" — resolve to the OS locale at apply time.
//! * `Some(code)` → BCP-47 / locale code matching one of the bundled `.po`
//!   directories under `i18n/`.
//!
//! The list of supported locales is generated from `i18n/` by `build.rs`;
//! see `language_table.rs` in `OUT_DIR`.

use slint::{ModelRc, SharedString, VecModel};

use crate::i18n::ctr;

// language_table.rs is generated by build.rs from the contents of `i18n/`.
include!(concat!(env!("OUT_DIR"), "/language_table.rs"));

/// Build the model shown by the language `ComboBox`. Index 0 is always the
/// "System" option; subsequent indices match the order of `LANGUAGES`.
///
/// Rebuilt on every language change so the "System" label is re-translated
/// against the newly-active language.
pub(crate) fn display_options() -> ModelRc<SharedString> {
    let mut entries: Vec<SharedString> = Vec::with_capacity(LANGUAGES.len() + 1);
    entries.push(ctr!("AppearancePreferences", "System"));
    entries.extend(LANGUAGES.iter().map(|(_, name)| SharedString::from(*name)));
    ModelRc::new(VecModel::from(entries))
}

/// Returns the index in `display_options` that corresponds to a given
/// preference. Unknown codes fall back to "System" (index 0).
pub(crate) fn index_for(pref: Option<&str>) -> i32 {
    let Some(code) = pref else {
        return 0;
    };
    LANGUAGES
        .iter()
        .position(|(c, _)| *c == code)
        .map(|i| (i + 1) as i32)
        .unwrap_or(0)
}

/// Maps a `display_options` index back to a preference value.
pub(crate) fn pref_for(index: i32) -> Option<String> {
    if index <= 0 {
        return None;
    }
    LANGUAGES
        .get((index - 1) as usize)
        .map(|(code, _)| (*code).to_string())
}

/// Apply a language preference to the running app.
///
/// `None` means "system": detect the OS locale via `sys_locale` and try
/// that. Falls back to the base language (e.g. `es` for `es-ES`) when the
/// exact locale tag has no bundle, mirroring Slint's own auto-detection.
///
/// Slint's `select_bundled_translation` requires that at least one
/// component already exists; the caller is responsible for that ordering.
pub(crate) fn apply(pref: Option<&str>) {
    let detected;
    let target: &str = match pref {
        Some(code) => code,
        None => {
            detected = sys_locale::get_locale().unwrap_or_default();
            &detected
        }
    };

    if slint::select_bundled_translation(target).is_ok() {
        return;
    }
    let base = base_language(target);
    if base != target && slint::select_bundled_translation(base).is_ok() {
        return;
    }
    // Nothing matched — fall back to the source language.
    let _ = slint::select_bundled_translation("");
}

fn base_language(locale: &str) -> &str {
    locale
        .find(['-', '_', '@'])
        .map_or(locale, |i| &locale[..i])
}

#[cfg(test)]
mod language_tests {
    use super::*;

    #[test]
    fn system_round_trips_through_index_zero() {
        assert_eq!(index_for(None), 0);
        assert_eq!(pref_for(0), None);
    }

    #[test]
    fn known_code_round_trips() {
        let idx = index_for(Some("es"));
        assert!(idx > 0);
        assert_eq!(pref_for(idx).as_deref(), Some("es"));
    }

    #[test]
    fn unknown_code_falls_back_to_system() {
        assert_eq!(index_for(Some("xx")), 0);
    }

    #[test]
    fn pref_for_out_of_range_is_system() {
        assert_eq!(pref_for(-1), None);
        assert_eq!(pref_for(9999), None);
    }

    #[test]
    fn base_language_strips_region() {
        assert_eq!(base_language("es-ES"), "es");
        assert_eq!(base_language("pt_BR"), "pt");
        assert_eq!(base_language("en@latin"), "en");
        assert_eq!(base_language("de"), "de");
    }
}
